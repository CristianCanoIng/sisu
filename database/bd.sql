CREATE INDEX idx_consultas_profesional
ON public.consultas(id_profesional);

CREATE INDEX idx_incapacidades_paciente
ON public.incapacidades(id_paciente);

CREATE INDEX idx_acompanamientos_paciente
ON public.acompanamientos(id_paciente);

CREATE INDEX idx_movimientos_inventario
ON public.movimiento_inventario(id_inventario);


